# -*- coding: utf-8 -*-
"""
법령 원문 스니펫 → 읽을 수 있게 줄바꿈.

왜 위험한가
-----------
법령 조문에는 **날짜가 섞여 있다** — "<신설 2014. 5. 28., 2016. 1. 19.>".
호 번호(`1.` `2.`)를 기준으로 자르면 이 날짜가 쪼개져 **원문이 훼손된 것처럼 보인다.**
조문을 인용하는 화면에서 그건 오탈자보다 나쁘다.

그래서 지키는 것 — **공백 외에는 한 글자도 더하거나 빼지 않는다.**
    "".join(원문.split()) == "".join(결과.split())
이 등식이 이 모듈의 계약이다. scripts/test_rag.py가 매번 검사한다.
줄을 엉뚱한 데서 끊는 실수는 할 수 있어도, 글자를 잃는 실수는 못 하게 만든다.

무엇을 기준으로 끊나
--------------------
· 조: `제12조(...)` — 여는 괄호까지 붙어 있어 모호하지 않다
· 항: `①②③…` — 다른 데 안 쓰인다
· 호: `1.` `2.` — **날짜를 먼저 봉인한 뒤에만** 끊는다
· 목(`가.` `나.` `다.`)은 **안 끊는다** — "…하여야 한다."의 '다.'와 구별이 안 된다.
  구별할 수 없으면 안 하는 게 맞다.
"""

import re

# ── 봉인 대상 ────────────────────────────────────────────────────────
# 2014. 5. 28. / 2016.1.19. — 조문 말미의 신설·개정 이력
_DATE = re.compile(r"\d{4}\.\s*\d{1,2}\.\s*\d{1,2}\.")
_SENTINEL = "\x00DATE{}\x00"

# ── 끊는 자리 ────────────────────────────────────────────────────────
# 제12조( · 제12조의2( — 여는 괄호가 있어야 조문 제목이다
_JO = re.compile(r"(?<!^)(?<!\n)\s*(제\d+조(?:의\d+)?\s*\()")
# 항 — 원 숫자는 법령에서 항 표시로만 쓰인다
_HANG = re.compile(r"(?<!^)(?<!\n)\s*([①-⑮])")
# 호 — 앞뒤가 공백인 한두 자리 숫자 + 마침표. 날짜는 이미 봉인돼 여기 안 걸린다.
_HO = re.compile(r"(?<=\s)(\d{1,2}\.)(?=\s)")


def format_legal(text: str) -> str:
    """법령 스니펫에 줄바꿈을 넣는다. 글자는 건드리지 않는다."""
    if not text:
        return text

    # ① 날짜 봉인 — 이걸 먼저 안 하면 "2014. 5. 28."이 세 줄로 찢어진다
    dates = []

    def _seal(m):
        dates.append(m.group(0))
        return _SENTINEL.format(len(dates) - 1)

    s = _DATE.sub(_seal, text)

    # ② 끊기
    s = _JO.sub(r"\n\n\1", s)
    s = _HANG.sub(r"\n\1", s)
    s = _HO.sub(r"\n\1", s)

    # ③ 날짜 복원
    for i, d in enumerate(dates):
        s = s.replace(_SENTINEL.format(i), d)

    # ④ 과한 빈 줄 정리
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s.strip()


def is_lossless(original: str, formatted: str) -> bool:
    """공백을 뺀 내용이 그대로인가 — 이 모듈의 유일한 계약."""
    return "".join(original.split()) == "".join(formatted.split())
